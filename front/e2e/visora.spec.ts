  const report = await (await page.request.get(`/api/analytics?project=${project.id}`)).json()
  expect(report.totals).toEqual({ pv: 3, uv: 1, sessions: 1, events: 1 })
  expect(report.dimensions.path.map((r: { name: string }) => r.name).sort()).toEqual(['/', '/dashboard', '/pricing'])
