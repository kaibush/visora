  await expect(page.getByText('signup_completed', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '趋势', exact: true }).click()
  await expect(page.getByRole('heading', { name: '访问趋势' })).toBeVisible()
  await page.goto('/pages')
  await expect(page.getByRole('heading', { name: '页面分析' })).toBeVisible()
  await page.getByRole('link', { name: '概览', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.screenshot({ path: testInfo.outputPath('visora-overview.png'), fullPage: true })
  await page.getByRole('link', { name: '访问明细', exact: true }).click()
  await expect(page.getByRole('cell', { name: '/dashboard', exact: true })).toBeVisible()
