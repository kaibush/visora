import { test, expect } from 'playwright/test'

test('create project, track a real SPA, inspect aggregate data, export CSV and log out', async ({ page, context }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录 Visora' })).toBeVisible()
  await page.getByLabel('管理密码').fill('visora-e2e-password-only')
  await page.getByRole('button', { name: '进入工作空间' }).click()
  await expect(page.getByRole('heading', { name: '访问概览' })).toBeVisible()
  await page.getByRole('link', { name: '项目管理' }).click()
  await page.getByRole('button', { name: '新建项目' }).click()
  await page.getByLabel('项目名称').fill('new-api E2E')
  await page.getByLabel('允许的网站来源').fill('http://127.0.0.1:4318')
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.getByRole('heading', { name: '保存 new-api E2E 的服务端密钥' })).toBeVisible()
  await page.getByRole('button', { name: '我已保存' }).click()
  const { projects } = await (await page.request.get('/api/projects')).json()
  const project = projects.find((p: { name: string }) => p.name === 'new-api E2E')
  const website = await context.newPage()
  const collected = website.waitForResponse((r) => r.url().includes('/api/collect/'))
  await website.goto(`http://127.0.0.1:4318/?site=${project.siteId}`)
  expect((await collected).status()).toBe(202)
  await website.evaluate(() => {
    history.pushState({}, '', '/dashboard?token=private#private')
    history.replaceState({}, '', '/dashboard?token=changed')
    history.pushState({}, '', '/pricing')
    const tracker = (window as unknown as { visora: { track: (name: string) => void } }).visora
    tracker.track('signup_completed')
  })
  await expect.poll(async () => (await (await page.request.get(`/api/events?project=${project.id}`)).json()).total).toBe(4)
  const report = await (await page.request.get(`/api/analytics?project=${project.id}`)).json()
  expect(report.totals).toEqual({ pv: 3, uv: 1, sessions: 1, events: 1 })
  expect(report.dimensions.path.map((r: { name: string }) => r.name).sort()).toEqual(['/', '/dashboard', '/pricing'])
  await page.getByRole('link', { name: '访问概览', exact: true }).click()
  await expect(page.getByText('signup_completed', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.screenshot({ path: testInfo.outputPath('visora-overview.png'), fullPage: true })
  await page.getByRole('link', { name: '访问明细', exact: true }).click()
  await expect(page.getByRole('cell', { name: '/dashboard', exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 CSV' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^visora-.*\.csv$/)
  await page.getByRole('link', { name: '接入指南', exact: true }).first().click()
  await expect(page.getByText(project.siteId, { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '服务端 API' }).click()
  await expect(page.getByText('Shell · 先设置 VISORA_SERVER_KEY')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('visora-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '登录 Visora' })).toBeVisible()
  expect((await page.request.get('/api/projects')).status()).toBe(401)
  expect(errors).toEqual([])
})

test('tracker respects privacy signals, hash routes and renews a session after inactivity', async ({ browser, request }) => {
  await request.post('/api/auth/login', { data: { password: 'visora-e2e-password-only' } })
  const { project } = await (await request.post('/api/projects', { data: { name: 'tracker privacy', origins: ['http://127.0.0.1:4318'] } })).json()
  const context = await browser.newContext()
  const page = await context.newPage()
  await page.goto(`http://127.0.0.1:4318/?site=${project.siteId}&hash=1#/home`)
  await expect.poll(async () => (await (await request.get(`/api/events?project=${project.id}`)).json()).total).toBe(1)
  await page.evaluate((siteId) => {
    sessionStorage.setItem(`visora:${siteId}:last`, String(Date.now() - 31 * 60000))
    location.hash = '/next?token=private'
  }, project.siteId)
  await expect.poll(async () => (await (await request.get(`/api/analytics?project=${project.id}`)).json()).totals.sessions).toBe(2)
  const denied = await browser.newContext()
  await denied.addInitScript(() => Object.defineProperty(navigator, 'doNotTrack', { get: () => '1' }))
  const deniedPage = await denied.newPage()
  await deniedPage.goto(`http://127.0.0.1:4318/?site=${project.siteId}`)
  await deniedPage.waitForLoadState('networkidle')
  expect(await deniedPage.evaluate(() => 'visora' in window)).toBe(false)
  expect((await (await request.get(`/api/events?project=${project.id}`)).json()).total).toBe(2)
  await context.close()
  await denied.close()
})
